// Throwaway key material for the prototype. Everything here is generated fresh
// on first run and lives in ./keys (gitignored). Never reuse these anywhere.
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { privateKeyToAccount } from "viem/accounts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const KEYS_DIR = join(ROOT, "keys");

function ensureDir() {
  if (!existsSync(KEYS_DIR)) mkdirSync(KEYS_DIR, { recursive: true, mode: 0o700 });
}

/** Create-or-load a named throwaway key file. */
export function loadOrCreateKey(name) {
  ensureDir();
  const path = join(KEYS_DIR, `${name}.json`);
  if (existsSync(path)) return JSON.parse(readFileSync(path, "utf8"));
  const k = {
    name,
    createdAt: new Date().toISOString(),
    // fresh classical (EVM owner) key
    eoaPrivateKey: "0x" + randomBytes(32).toString("hex"),
    // fresh post-quantum master seed for the SHRINCS key bundle
    pqMasterSeed: "0x" + randomBytes(32).toString("hex"),
    note: "THROWAWAY TESTNET KEY - generated by prototype, do not reuse",
  };
  writeFileSync(path, JSON.stringify(k, null, 2), { mode: 0o600 });
  return k;
}

export function eoaFor(key) {
  return privateKeyToAccount(key.eoaPrivateKey);
}

export function hexToBytes(hex) {
  const h = hex.startsWith("0x") ? hex.slice(2) : hex;
  return Uint8Array.from(Buffer.from(h, "hex"));
}
export function bytesToHex(b) {
  return "0x" + Buffer.from(b).toString("hex");
}
