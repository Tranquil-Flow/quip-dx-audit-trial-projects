// Generates brand-new THROWAWAY testnet keys into ./keys/keys.json (never overwrites).
import { existsSync, writeFileSync } from "node:fs";
import { generatePrivateKey, privateKeyToAddress } from "viem/accounts";
import { generateMnemonic } from "@quip.network/ethereum-sdk/v1/shrincs";

const out = "keys/keys.json";
if (existsSync(out)) { console.log(`${out} exists; not overwriting`); process.exit(0); }
const party = (name: string) => {
  const eoaPrivateKey = generatePrivateKey();
  return { name, eoaPrivateKey, eoaAddress: privateKeyToAddress(eoaPrivateKey), shrincsMnemonic: generateMnemonic() };
};
const keys = { note: "THROWAWAY TESTNET KEYS ONLY — generated by src/genkeys.ts", alice: party("alice"), bob: party("bob") };
writeFileSync(out, JSON.stringify(keys, null, 2), { mode: 0o600 });
console.log("alice EOA", keys.alice.eoaAddress, "\nbob   EOA", keys.bob.eoaAddress);
